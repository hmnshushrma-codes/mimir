/** Small deterministic string hash — not cryptographic, just stable enough
 *  for picking a palette slot or a fallback id from a string. */
export function hashString(input: string): number {
  let hash = 0;
  for (let i = 0; i < input.length; i++) {
    hash = (hash * 31 + input.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}
